def feats(y,u):
    a,b=y;c,d=u
    return [1,a,b,c,d,a*a,b*b,a*b,c*c,d*d,c*d,a*c,a*d,b*c,b*d,np.sin(a),np.sin(b),np.tanh(c),np.tanh(d)]
G=np.linspace(-3,3,13)
TG=np.array([0.33,0.7])
def controlar(lecturas,memoria):
    b=memoria.get('b',np.zeros(2))
    if 'p' in memoria:
        b=0.7*b+0.3*(np.array(lecturas)-memoria['p'])
    memoria['b']=b
    best=None
    for c in G:
        for d in G:
            p=W@np.array(feats(lecturas,(c,d)))+b
            p2=W@np.array(feats(p,(c,d)))+b
            e=np.sum(((p-TG)/[1,3])**2)+np.sum(((p2-TG)/[1,3])**2)
            if best is None or e<best[0]: best=(e,[float(c),float(d)],p)
    memoria['p']=best[2]-b
    return best[1]
